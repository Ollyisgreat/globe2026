// Regenerates app/src/main/assets/roster-fallback.js from a saved copy of the
// judging site's index.html. Usage: node tools/build-roster.js path/to/index.html
// The TV app always tries to load the live roster from the site first; this
// file is only used if the site can't be reached when the app starts.
const fs = require('fs');
const path = require('path');
const { parseRoster } = require('../app/src/main/assets/roster-parse.js');
const html = fs.readFileSync(process.argv[2], 'utf8');
const roster = parseRoster(html);
const out = path.join(__dirname, '../app/src/main/assets/roster-fallback.js');
fs.writeFileSync(out, '// Generated by tools/build-roster.js — offline copy of the delegate list.\nwindow.FALLBACK_ROSTER = ' + JSON.stringify(roster, null, 1) + ';\n');
console.log('Wrote', roster.candidates.length, 'delegates,', roster.fields.length, 'categories, judges', roster.judges.join(', '));
